//! M/S trap 汇编入口。

// 陷阱入口汇编。
//
// 布局：Context 在栈上，35×4=140 字节，分配 144（16 对齐）。
// slot 2（offset 8）存原始 sp，恢复时从 gpr[2] 读回（支持上下文切换）。
// x5（t0）先存再用作 scratch；恢复时最后恢复。
#[cfg(target_arch = "riscv32")]
core::arch::global_asm!(
    ".section .text.trap",
    ".align 2",
    ".global __am_asm_trap",
    "__am_asm_trap:",
    // 分配 Context（144 字节，16 对齐）
    "addi sp, sp, -144",
    // 存 x1（ra）到 slot 1
    "sw ra, 4(sp)",
    // 存 x3-x5（gp/tp/t0），t0 须先存再作 scratch
    "sw gp, 12(sp)",
    "sw tp, 16(sp)",
    "sw t0, 20(sp)",
    // 存 x6-x31
    "sw t1, 24(sp)",
    "sw t2, 28(sp)",
    "sw s0, 32(sp)",
    "sw s1, 36(sp)",
    "sw a0, 40(sp)",
    "sw a1, 44(sp)",
    "sw a2, 48(sp)",
    "sw a3, 52(sp)",
    "sw a4, 56(sp)",
    "sw a5, 60(sp)",
    "sw a6, 64(sp)",
    "sw a7, 68(sp)",
    "sw s2, 72(sp)",
    "sw s3, 76(sp)",
    "sw s4, 80(sp)",
    "sw s5, 84(sp)",
    "sw s6, 88(sp)",
    "sw s7, 92(sp)",
    "sw s8, 96(sp)",
    "sw s9, 100(sp)",
    "sw s10, 104(sp)",
    "sw s11, 108(sp)",
    "sw t3, 112(sp)",
    "sw t4, 116(sp)",
    "sw t5, 120(sp)",
    "sw t6, 124(sp)",
    // 存原始 sp 到 slot 2
    "addi t0, sp, 144",
    "sw t0, 8(sp)",
    // 存 CSR
    "csrr t0, mcause",
    "sw t0, 128(sp)",
    "csrr t0, mstatus",
    "sw t0, 132(sp)",
    "csrr t0, mepc",
    "sw t0, 136(sp)",
    // 调用 __am_irq_handle(sp)
    "mv a0, sp",
    "call __am_irq_handle",
    // 切到返回的 Context
    "mv sp, a0",
    // 恢复 CSR
    "lw t0, 132(sp)",
    "csrw mstatus, t0",
    "lw t0, 136(sp)",
    "csrw mepc, t0",
    "lw t0, 128(sp)",
    "csrw mcause, t0",
    // 恢复 x1, x3-x4
    "lw ra, 4(sp)",
    "lw gp, 12(sp)",
    "lw tp, 16(sp)",
    // 恢复 x6-x31（跳过 x5/t0）
    "lw t1, 24(sp)",
    "lw t2, 28(sp)",
    "lw s0, 32(sp)",
    "lw s1, 36(sp)",
    "lw a0, 40(sp)",
    "lw a1, 44(sp)",
    "lw a2, 48(sp)",
    "lw a3, 52(sp)",
    "lw a4, 56(sp)",
    "lw a5, 60(sp)",
    "lw a6, 64(sp)",
    "lw a7, 68(sp)",
    "lw s2, 72(sp)",
    "lw s3, 76(sp)",
    "lw s4, 80(sp)",
    "lw s5, 84(sp)",
    "lw s6, 88(sp)",
    "lw s7, 92(sp)",
    "lw s8, 96(sp)",
    "lw s9, 100(sp)",
    "lw s10, 104(sp)",
    "lw s11, 108(sp)",
    "lw t3, 112(sp)",
    "lw t4, 116(sp)",
    "lw t5, 120(sp)",
    "lw t6, 124(sp)",
    // 最后恢复 t0
    "lw t0, 20(sp)",
    // 从 gpr[2] 恢复 sp（支持上下文切换）
    "lw sp, 8(sp)",
    "mret",
);

